"""Write web/src/hud/resultsFacts.ts from results/, or check that it is current.

The game-over screen shows a win rate only from this file, and always with its table size.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
TARGET = ROOT / "web" / "src" / "hud" / "resultsFacts.ts"

SOURCES = {
    ("ppo", 2): ("rl_eval_summary_two_player_v2_all.json", "two_player"),
    ("dqn", 2): ("ppo_vs_dqn.json", "DQN"),
    ("ppo", 4): ("rl_eval_summary_main_v2_all.json", "four_player"),
}


def _stats(file: str, key: str) -> dict:
    data = json.loads((RESULTS / file).read_text(encoding="utf-8"))
    return data["evaluation"][key] if file == "ppo_vs_dqn.json" else data[key]


def build_facts() -> list[dict]:
    """Return one fact per (agent, table size) that `results/` backs up."""
    two_player = RESULTS / "rl_eval_summary_two_player_v2_all.json"
    bots = json.loads(two_player.read_text(encoding="utf-8"))["bots"]
    facts = []
    for (agent, players), (file, key) in SOURCES.items():
        stats = _stats(file, key)
        facts.append(
            {
                "agent": agent,
                "players": players,
                "winRate": round(stats["win_rate"] * 100, 1),
                "ciLow": round(stats["ci_low"] * 100, 1),
                "ciHigh": round(stats["ci_high"] * 100, 1),
                "games": stats["games"],
                "bots": bots,
                "source": file,
            }
        )
    return facts


def render() -> str:
    """Return the TypeScript file text."""
    body = json.dumps(build_facts(), indent=2)
    return (
        "// Generated by scripts/export_hud_facts.py from results/. Do not edit by hand.\n\n"
        "export interface ResultsFact {\n"
        '  agent: "ppo" | "dqn";\n'
        "  players: number;\n"
        "  winRate: number;\n"
        "  ciLow: number;\n"
        "  ciHigh: number;\n"
        "  games: number;\n"
        "  bots: number;\n"
        "  source: string;\n"
        "}\n\n"
        f"export const RESULTS_FACTS: ResultsFact[] = {body};\n"
    )


def main() -> int:
    """Write the file, or with --check exit 1 if it differs."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{TARGET} is out of date. Run: python scripts/export_hud_facts.py")
            return 1
        print("resultsFacts.ts is up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
